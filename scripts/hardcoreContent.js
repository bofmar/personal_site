const exImagePath = "../resources/icons/24px-Trial.png";
const raidImagePath = "../resources/icons/20px-Raid.png";
const tankImagePath = "../resources/icons/20px-Tank_role.png";
const healerImagePath = "../resources/icons/20px-Healer_role.png";
const dpsImagePath = "../resources/icons/20px-DPS_role.png";

const container = document.querySelector(".flex-container");

function createListItem(data, duty_type) {
    const li = document.createElement("li");

    const duty_icon = document.createElement("img");
    duty_icon.src = duty_type === "ex" ? exImagePath : raidImagePath;
    li.appendChild(duty_icon);

    const span = document.createElement("span");
    span.innerText = data.name;
    li.appendChild(span);

    data.roles.map(role => {
        const roleImage = document.createElement("img");
        roleImage.src = role.role_name === "tank" ? tankImagePath : role.role_name === "healer" ? healerImagePath : dpsImagePath;
        if (!role.cleared) roleImage.classList.add("uncleared");
        li.appendChild(roleImage);
    });
    return li;
}

function createList(listName, duties, duty_type) {
    const title = document.createElement("h2");
    title.innerText = listName;
    const list = document.createElement("ul");
    duties.map( duty => {
        const item = createListItem(duty, duty_type);
        list.appendChild(item)
    })

    return [title, list];
}

for (const expansion in content) {
    // create the sectrion
    const section = document.createElement("section");
    section.classList.add("clears-section");
    // create the title
    const title = document.createElement("h1");
    title.innerText = content[expansion].expansionName;
    section.appendChild(title);
    // create lists
    if (content[expansion].extremes.length !== 0) {
        const listElements = createList("Extremes", content[expansion].extremes, "ex");
        listElements.map( e => {
            section.appendChild(e);
        })
    }
    if (content[expansion].arr_raids.length !== 0) {
        const listElements = createList("ARR Raids", content[expansion].arr_raids, "arr_raids");
        listElements.map( e => {
            section.appendChild(e);
        })
    }
    if (content[expansion].savage.length !== 0) {
        const listElements = createList("Savage Tier", content[expansion].savage, "savage");
        listElements.map( e => {
            section.appendChild(e);
        })
    }
    if (content[expansion].ultimate.length !== 0) {
        const listElements = createList("Ultimate", content[expansion].ultimate, "ultimate");
        listElements.map( e => {
            section.appendChild(e);
        })
    }
    if (content[expansion].chaotics.length !== 0) {
        const listElements = createList("Chaotic", content[expansion].chaotics, "chaotic");
        listElements.map( e => {
            section.appendChild(e);
        })
    }

    container.appendChild(section);
}